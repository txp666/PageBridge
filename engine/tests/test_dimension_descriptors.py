"""Source-proven dimensional prose must not be mistaken for an opaque ID."""
import unittest

try:
    from .test_translation_guard import guard, translator, paragraph, ParagraphTranslateTracker
    from .test_numeric_recovery import source_input, formula
except ImportError:
    from test_translation_guard import guard, translator, paragraph, ParagraphTranslateTracker
    from test_numeric_recovery import source_input, formula


class DimensionDescriptorTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        guard.install()

    def setUp(self):
        guard._states.clear()
        guard._counters.clear()

    def test_proven_dimensional_representation_accepts_chinese_without_model_retry(self):
        for dimension, chinese in ((2, '二'), (3, '三')):
            source = source_input(f'The analysis gives a {dimension}D graphical representation of the variation.')
            for term in (f'{chinese}维图形表示', f'{dimension}维的图形表示', f'{dimension}D图形表示'):
                with self.subTest(term=term):
                    output = f'该分析给出了变化的{term}。'
                    p, instance = paragraph(source), translator([])
                    instance.post_translate_paragraph(p, ParagraphTranslateTracker(), source, output)
                    self.assertEqual(p.unicode, output)
                    self.assertEqual(instance.calls, [])
                    self.assertEqual(guard.snapshot()['unresolvedCount'], 0)

    def test_missing_changed_or_duplicated_dimension_is_rejected(self):
        source = source_input('The analysis gives a 3D graphical representation of the variation.')
        for output in ('该分析给出了变化的图形表示。', '该分析给出了变化的二维图形表示。',
                       '该分析给出了变化的3D图形表示及三维图形表示。'):
            with self.subTest(output=output), self.assertRaisesRegex(
                    guard.PlaceholderIntegrityError, 'scientific-identifier-changed'):
                guard._check_body_translation(translator([]), paragraph(source), source, output)

    def test_other_scientific_identifiers_keep_exact_spelling_and_multiplicity(self):
        source = source_input('The 5BLC and LC6 data give a 3D graphical representation of the variation.')
        valid = '5BLC和LC6数据给出了变化的三维图形表示。'
        guard._check_body_translation(translator([]), paragraph(source), source, valid)
        for bad in (valid.replace('5BLC', '6BLC'), valid.replace('LC6', 'LC'), valid + '5BLC。'):
            with self.subTest(output=bad), self.assertRaisesRegex(
                    guard.PlaceholderIntegrityError, 'scientific-identifier-changed'):
                guard._check_body_translation(translator([]), paragraph(source), source, bad)

    def test_model_name_and_nonrepresentation_uses_do_not_prove_dimensions(self):
        for text in ('The device name is Model3D and its code remains unchanged.',
                     'The product is named 3D and its code remains unchanged.'):
            source = source_input(text)
            with self.subTest(source=text), self.assertRaisesRegex(
                    guard.PlaceholderIntegrityError, 'scientific-identifier-changed'):
                guard._check_body_translation(translator([]), paragraph(source), source,
                                               '该设备采用三维图形表示，其代码保持不变。')

    def test_dimension_conversion_cannot_consume_a_separate_same_named_identifier(self):
        for dimension, chinese in ((2, '二'), (3, '三')):
            source = source_input(f'The {dimension}D graphical representation is generated by a model named {dimension}D.')
            good = f'{chinese}维图形表示由名为{dimension}D的模型生成。'
            guard._check_body_translation(translator([]), paragraph(source), source, good)
            for bad in (f'{chinese}维图形表示由名为{chinese}维图形表示的模型生成。',
                        good + f'另附{chinese}维图形表示。'):
                with self.subTest(output=bad), self.assertRaisesRegex(
                        guard.PlaceholderIntegrityError, 'scientific-identifier-changed'):
                    guard._check_body_translation(translator([]), paragraph(source), source, bad)

    def test_each_source_dimension_descriptor_supplies_only_one_conversion(self):
        source = source_input('A 3D representation and another 3D graphical representation use the model named 3D.')
        for good in ('三维表示和另一个三维图形表示使用名为3D的模型。',
                     '3D表示和另一个三维图形表示使用名为3D的模型。'):
            guard._check_body_translation(translator([]), paragraph(source), source, good)
        bad = '三维表示和另一个三维图形表示使用名为三维表示的模型。'
        with self.assertRaisesRegex(guard.PlaceholderIntegrityError, 'scientific-identifier-changed'):
            guard._check_body_translation(translator([]), paragraph(source), source, bad)

    def test_actual_wind_page_seven_dimension_paragraph_stays_translatable(self):
        source = source_input('A second analysis of Table 5 wouldbe to identify the time series on the winds cube, '
                              'giving a 3D graphical representation of the circulation variation among these five days.')
        good = '对表5的另一项分析是在风立方体上识别时间序列，从而给出这五天之间环流变化的三维图形表示。'
        p, instance = paragraph(source), translator([])
        instance.post_translate_paragraph(p, ParagraphTranslateTracker(), source, good)
        self.assertEqual(p.unicode, good)
        self.assertEqual(instance.calls, [])

    def test_formula_and_url_dimensions_are_opaque(self):
        f = formula(1, '3D graphical representation')
        source = source_input('The expression is {v1}; the code 3D remains unchanged.', [f])
        self.assertEqual(guard._prose_scientific_identifiers(source, '三维图形表示{v1}。'), {})
        source = source_input('See https://example.invalid/3D%20graphical%20representation for the data.')
        self.assertEqual(guard._prose_scientific_identifiers(source, '三维图形表示。'), {})


if __name__ == '__main__':
    unittest.main()
